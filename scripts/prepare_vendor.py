"""Prepare web/vendor/: everything the PWA loads, served from the same site.

- Pyodide runtime and distribution packages (PyMuPDF included, with dependencies)
  from Pyodide's CDN
- pure-Python wheels from PyPI (pdf2docx, python-docx)
- the python/pdf2word engine
- manifest.json (what to load) and precache.js (what to cache for offline use)

Every downloaded file is checked against sha256 (Pyodide lock file / PyPI JSON API).
Runs at build time only: the user's browser never contacts a CDN or PyPI.

Usage: python scripts/prepare_vendor.py
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
VENDOR = WEB / "vendor"

# Pyodide distribution packages needed by the engine (dependencies resolved from the lock file).
# PyMuPDF is built and tested by the Pyodide project (0.28.3 -> PyMuPDF 1.26.3).
PYODIDE_PACKAGES = ["pymupdf", "numpy", "opencv-python", "fonttools", "lxml", "typing-extensions"]
# Pure-Python wheels from PyPI, pinned. Installed without dependencies:
# pdf2docx 0.5.13 declares PyMuPDF>=1.26.7, but with 1.26.3 it produces identical DOCX (see ADR 0002).
PYPI_WHEELS = {"pdf2docx": "0.5.13", "python-docx": "1.2.0"}
RUNTIME = ["pyodide.js", "pyodide.asm.js", "pyodide.asm.wasm", "python_stdlib.zip", "pyodide-lock.json"]
# App shell: precached together with vendor/.
SHELL = ["./", "index.html", "app.js", "i18n.js", "worker.js", "style.css", "manifest.webmanifest",
         "icons/icon-192.png", "icons/icon-512.png", "icons/icon-maskable-512.png"]


def download(url: str, dest: Path, sha256: str | None = None) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    with urllib.request.urlopen(url) as r:
        data = r.read()
    if sha256 and hashlib.sha256(data).hexdigest() != sha256:
        sys.exit(f"sha256 mismatch for {url}")
    dest.write_bytes(data)
    print(f"  {len(data) / 1048576:6.2f} MB  {dest.relative_to(WEB)}")


def resolve(lock: dict, names: list[str]) -> list[str]:
    packages = lock["packages"]
    seen: list[str] = []

    def visit(n: str) -> None:
        n = n.lower().replace("_", "-")
        if n in seen:
            return
        if n not in packages:
            sys.exit(f"package {n!r} not in the Pyodide lock file")
        for d in packages[n].get("depends", []):
            visit(d)
        seen.append(n)

    for n in names:
        visit(n)
    return seen


def main() -> None:
    argparse.ArgumentParser(description=__doc__.splitlines()[0]).parse_args()

    version = (WEB / "pyodide-version.txt").read_text().strip()
    cdn = f"https://cdn.jsdelivr.net/pyodide/v{version}/full/"
    if VENDOR.exists():
        shutil.rmtree(VENDOR)

    print(f"Pyodide {version}: runtime")
    for f in RUNTIME:
        download(cdn + f, VENDOR / "pyodide" / f)
    lock = json.loads((VENDOR / "pyodide" / "pyodide-lock.json").read_text())

    names = resolve(lock, PYODIDE_PACKAGES)
    print(f"Pyodide packages: {', '.join(names)}")
    for n in names:
        p = lock["packages"][n]
        download(cdn + p["file_name"], VENDOR / "pyodide" / p["file_name"], p["sha256"])

    wheels = []
    print("PyPI wheels")
    for name, ver in PYPI_WHEELS.items():
        with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{ver}/json") as r:
            info = json.load(r)
        whl = next(u for u in info["urls"] if u["packagetype"] == "bdist_wheel" and u["filename"].endswith("none-any.whl"))
        download(whl["url"], VENDOR / "wheels" / whl["filename"], whl["digests"]["sha256"])
        wheels.append(f"vendor/wheels/{whl['filename']}")

    engine = []
    (VENDOR / "pdf2word").mkdir(parents=True)
    for py in sorted((ROOT / "python" / "pdf2word").glob("*.py")):
        shutil.copy2(py, VENDOR / "pdf2word" / py.name)
        engine.append(f"vendor/pdf2word/{py.name}")

    (VENDOR / "manifest.json").write_text(json.dumps({
        "pyodide": version,
        "packages": names,
        "wheels": wheels,
        "engine": engine,
    }, indent=2))

    # Version = hash of everything cached: when it changes, the service worker updates.
    files = SHELL + sorted(str(p.relative_to(WEB)) for p in VENDOR.rglob("*") if p.is_file())
    h = hashlib.sha256()
    for f in files:
        if f != "./":
            h.update(f.encode())
            h.update((WEB / f).read_bytes())
    total = sum((WEB / f).stat().st_size for f in files if f != "./")
    (VENDOR / "precache.js").write_text(
        "// Generated by scripts/prepare_vendor.py: do not edit.\n"
        f"self.PRECACHE = {json.dumps({'version': h.hexdigest()[:12], 'bytes': total, 'files': files}, indent=1)};\n"
    )
    print(f"Total to cache: {total / 1048576:.1f} MB, version {h.hexdigest()[:12]}")


if __name__ == "__main__":
    main()
